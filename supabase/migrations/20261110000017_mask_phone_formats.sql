-- Boleia - маска телефонов: обычные форматы записи (ТЗ разделы 6, 8)
--
-- 0016 допускал между цифрами один пробел, точку или дефис. "(923) 456-789", "+244 (923) 456 789",
-- "923 - 456 - 789" и двойной пробел проходили как есть. Теперь между цифрами до трёх символов из
-- пробела, точки, дефиса и скобок.

create or replace function public.mask_text(p_body text)
returns text language sql immutable as $$
  select regexp_replace(
           regexp_replace(p_body, '(https?://\S+|wa\.me/?\S*)', '[oculto]', 'gi'),
           -- запятая и слэш не разделители: иначе под маску попадают списки цен и даты
           '(?<!\d)(?:\(?(?:\+|00)?244[\s.()-]{0,3}\d(?:[\s.()-]{0,3}\d){8}|\(?9(?:[\s.()-]{0,3}\d){8})(?!\d)', '[oculto]', 'g')
$$;
